"""zsh completion generated from the argparse parser, so it never drifts from the CLI.

    eval "$(gittool completion zsh)"     # after compinit (e.g. after oh-my-zsh.sh)
"""

from __future__ import annotations

import argparse
from pathlib import Path

# Completers for options whose values gittool knows better than "a word".
# `_gittool_branches` / `_gittool_ai_tools` are defined in the generated script.
VALUE_COMPLETERS = {
    "branch": "_gittool_branches",
    "base": "_gittool_branches",
    "ai": "_gittool_ai_tools",
}

PRELUDE = r"""
_gittool_repo() {
  # the path positional if one was typed (words[1] is the action), else cwd
  local w
  for w in "${(@)words[2,CURRENT-1]}"; do
    [[ $w != -* && -d $w ]] && { print -r -- $w; return }
  done
  print -r -- .
}

_gittool_branches() {
  local -a branches
  branches=(${(f)"$(git -C "$(_gittool_repo)" for-each-ref --format='%(refname:short)' \
    refs/heads refs/remotes 2>/dev/null)"})
  branches=(${branches:#*/HEAD})
  _describe -t branches 'branch' branches
}

_gittool_ai_tools() {
  local -a tools
  tools=(claude agy ${(s:,:)GITTOOL_AI_TOOLS// /})
  _describe -t ai-tools 'AI tool' tools
}
"""


def _q(text: str) -> str:
    """Single-quote for zsh."""
    return "'" + text.replace("'", "'\\''") + "'"


def _desc(text: str | None) -> str:
    """Text safe inside an _arguments [...] description or a name:desc pair."""
    return " ".join((text or "").split()).replace("\\", "\\\\").replace("[", "\\[") \
        .replace("]", "\\]").replace(":", "\\:")


def _value_spec(action: argparse.Action) -> str:
    """':message:action' for an option or positional that takes a value."""
    if action.choices:
        return f":{action.dest}:({' '.join(map(str, action.choices))})"
    completer = VALUE_COMPLETERS.get(action.dest)
    if completer is None:
        completer = "_files" if action.type is Path else (
            "_directories" if action.dest == "path" else "_default")
    metavar = action.metavar if isinstance(action.metavar, str) else None
    message = _desc((metavar or action.dest).lower())
    return f":{message}:{completer}"


def _argument_specs(parser: argparse.ArgumentParser) -> list[str]:
    exclusive: dict[int, list[str]] = {}
    for group in parser._mutually_exclusive_groups:  # noqa: SLF001 - no public API for this
        names = [o for a in group._group_actions for o in a.option_strings]  # noqa: SLF001
        for a in group._group_actions:  # noqa: SLF001
            exclusive[id(a)] = names

    specs: list[str] = []
    for action in parser._actions:  # noqa: SLF001
        if isinstance(action, argparse._SubParsersAction):  # noqa: SLF001
            continue
        help_text = "" if action.help == argparse.SUPPRESS else _desc(action.help)
        takes_value = action.nargs != 0
        if not action.option_strings:  # positional
            optional = action.nargs in ("?", "*")
            specs.append(_q(f"{':' if optional else ''}{_value_spec(action)}"))
            continue
        excl = " ".join(exclusive.get(id(action), action.option_strings))
        value = _value_spec(action) if takes_value else ""
        if len(action.option_strings) == 1:
            specs.append(_q(f"({excl}){action.option_strings[0]}[{help_text}]{value}"))
        else:
            opts = ",".join(action.option_strings)
            specs.append(f"{_q(f'({excl})')}{{{opts}}}{_q(f'[{help_text}]{value}')}")
    return specs


def zsh_script(parser: argparse.ArgumentParser, prog: str = "gittool") -> str:
    sub = next(a for a in parser._actions if isinstance(a, argparse._SubParsersAction))  # noqa: SLF001
    helps = {choice.dest: choice.help for choice in sub._choices_actions}  # noqa: SLF001

    actions = "\n".join(f"    {_q(f'{name}:{_desc(helps.get(name))}')}" for name in sub.choices)
    cases = []
    for name, subparser in sub.choices.items():
        specs = " \\\n        ".join(_argument_specs(subparser))
        cases.append(f"      {name})\n        _arguments -s \\\n        {specs} ;;")

    return f"""#compdef {prog}
# Generated by `{prog} completion zsh`; do not edit.
{PRELUDE}
_{prog}() {{
  local curcontext=$curcontext state line ret=1
  local -a actions
  actions=(
{actions}
  )
  _arguments -C \\
    '(- *)'{{-h,--help}}'[show help]' \\
    '1:action:->action' \\
    '*::argument:->args' && ret=0
  case $state in
    action) _describe -t actions '{prog} action' actions && ret=0 ;;
    args)
      curcontext=${{curcontext%:*:*}}:{prog}-$words[1]:
      case $words[1] in
{chr(10).join(cases)}
      esac && ret=0 ;;
  esac
  return ret
}}

if (( $+functions[compdef] )); then
  compdef _{prog} {prog}
else
  print -u2 "{prog}: run compinit before eval \\"\\$({prog} completion zsh)\\""
fi
"""
